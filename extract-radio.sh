# Makes vendor/oneplus/guacamoleg: the 5G model's own firmware, which the LineageOS zip flashes (as guacamole's does).
# Usage: extract-radio.sh <OxygenOS full OTA zip> <LineageOS tree>
# The OTA is the last one for the GM1920 (EEA): OnePlus7ProNROxygen_21.E.31_OTA_031_all_2111271509_64912a56fefe.zip,
# OxygenOS 10.0.15, MD5 443079369e983608765e5627f14986bf. Its modem image carries the SDX50M's firmware (image/sdx50m),
# which the OnePlus 7 Pro's does not. Nothing here is redistributed: the output stays in the local tree.
set -euo pipefail
OTA=$(realpath "${1:?usage: extract-radio.sh <OTA zip> <LineageOS tree>}"); TOP=$(realpath "${2:?usage: extract-radio.sh <OTA zip> <LineageOS tree>}")
OUT=$TOP/vendor/oneplus/guacamoleg
FW="LOGO abl aop bluetooth cmnlib cmnlib64 devcfg dsp hyp keymaster modem qupfw storsec tz xbl xbl_config"
EXTRACTOR=${OTA_EXTRACTOR:-$TOP/out/host/linux-x86/bin/ota_extractor}
[ -x "$EXTRACTOR" ] || EXTRACTOR=$(command -v ota_extractor) || { echo "no ota_extractor: build it (m ota_extractor)" >&2; exit 1; }
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
unzip -q -o "$OTA" payload.bin -d "$T"
grep -q "^ota-id=OnePlus7ProNROxygen_" <(unzip -p "$OTA" META-INF/com/android/metadata) || { echo "not a OnePlus 7 Pro 5G OTA" >&2; exit 1; }
"$EXTRACTOR" -payload "$T/payload.bin" -output_dir "$T" -partitions "${FW// /,}" >/dev/null 2>&1
rm -rf "$OUT"; mkdir -p "$OUT/radio"
{
    echo "# Generated by device/oneplus/guacamoleg/extract-radio.sh: the OnePlus 7 Pro 5G's firmware, OxygenOS 10.0.15"
    echo "LOCAL_PATH := \$(call my-dir)"
    echo "ifeq (\$(TARGET_DEVICE),guacamoleg)"
    for p in $FW; do
        mv "$T/$p.img" "$OUT/radio/"
        echo "\$(call add-radio-file-sha1-checked,radio/$p.img,$(sha1sum "$OUT/radio/$p.img" | cut -d' ' -f1))"
    done
    echo "endif"
} > "$OUT/Android.mk"
{
    echo "# Generated by device/oneplus/guacamoleg/extract-radio.sh"
    echo "AB_OTA_PARTITIONS += \\"
    for p in $FW; do echo "    $p \\"; done
    echo
} > "$OUT/BoardConfigVendor.mk"
# The SDX50M's loader (mdm_helper, which runs ks to send it its firmware): the 5G model's own, in place of the
# OnePlus 7 Pro's (sm8150-common, left out by patches/vendor_oneplus_sm8150-common), never paired with this modem.
"$EXTRACTOR" -payload "$T/payload.bin" -output_dir "$T" -partitions vendor >/dev/null 2>&1
mkdir -p "$OUT/proprietary/bin"
for f in bin/ks bin/mdm_helper; do
    debugfs -R "dump /$f $OUT/proprietary/$f" "$T/vendor.img" >/dev/null 2>&1
    [ -s "$OUT/proprietary/$f" ] || { echo "$f not found in the OTA's vendor" >&2; exit 1; }
done
rm -f "$T/vendor.img"
cat > "$OUT/Android.bp" <<'EOF'
// Generated by device/oneplus/guacamoleg/extract-radio.sh: the SDX50M's loader from OxygenOS 10.0.15
cc_prebuilt_binary {
    name: "ks_guacamoleg", stem: "ks", owner: "oneplus", vendor: true,
    srcs: ["proprietary/bin/ks"], compile_multilib: "64", check_elf_files: false, strip: { none: true },
}
cc_prebuilt_binary {
    name: "mdm_helper_guacamoleg", stem: "mdm_helper", owner: "oneplus", vendor: true,
    srcs: ["proprietary/bin/mdm_helper"], compile_multilib: "64", check_elf_files: false, strip: { none: true },
}
EOF
{
    echo "# Generated by device/oneplus/guacamoleg/extract-radio.sh: the firmware (radio/) and the SDX50M's loader"
    echo "PRODUCT_PACKAGES += ks_guacamoleg mdm_helper_guacamoleg"
} > "$OUT/guacamoleg-vendor.mk"
ls "$OUT/radio" "$OUT/proprietary"/*
